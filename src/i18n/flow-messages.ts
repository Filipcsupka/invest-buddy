export function getFlowMessages(locale: Locale): FlowMessages {
  return locale === "sk" ? sk : en;
}

/** ISO 3166 alpha-3 to alpha-2 for the default indicator countries, so their names come from Intl.DisplayNames. */
const ISO3: Record<string, string> = { USA: "US", DEU: "DE", FRA: "FR", GBR: "GB", JPN: "JP", CHN: "CN", SVK: "SK", CZE: "CZ", ITA: "IT", ESP: "ES", POL: "PL", AUT: "AT", NLD: "NL", CAN: "CA" };

/** Localized country name for an ISO alpha-2 or alpha-3 code; the code itself when unknown. */
export function countryName(locale: Locale, code: string, fallback?: string | null): string {
  const two = code.length === 3 ? ISO3[code.toUpperCase()] : code.toUpperCase();
  if (two && /^[A-Z]{2}$/.test(two)) {
    try { return new Intl.DisplayNames([locale === "sk" ? "sk-SK" : "en-GB"], { type: "region" }).of(two) ?? fallback ?? code; } catch { /* fall through */ }
  }
  return fallback ?? code;
}
