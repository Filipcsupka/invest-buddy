-- Market reference symbols were checked against EODHD exchange-symbol-list/INDX, FOREX and CC on 2026-11-06.
CREATE TABLE tracked_assets (
  vendor_symbol text PRIMARY KEY,
  asset_class text NOT NULL CHECK (asset_class IN ('index','fx','crypto')),
  name text NOT NULL,
  currency text,
  exchange text NOT NULL,
  enabled boolean NOT NULL DEFAULT true,
  sort integer NOT NULL DEFAULT 0,
  source_id text NOT NULL DEFAULT 'eodhd' REFERENCES data_sources(id)
);
CREATE TABLE asset_bars (
  vendor_symbol text NOT NULL REFERENCES tracked_assets(vendor_symbol),
  bar_date date NOT NULL,
  open numeric, high numeric, low numeric, close numeric NOT NULL,
  volume numeric,
  currency text,
  source_id text NOT NULL DEFAULT 'eodhd' REFERENCES data_sources(id),
  display_allowed boolean NOT NULL DEFAULT false,
  PRIMARY KEY (vendor_symbol, bar_date)
);
CREATE INDEX IF NOT EXISTS asset_bars_recent ON asset_bars(vendor_symbol, bar_date DESC);
CREATE TABLE eodhd_call_log (
  job text NOT NULL,
  run_date date NOT NULL,
  calls integer NOT NULL DEFAULT 0 CHECK (calls >= 0),
  source_id text NOT NULL DEFAULT 'eodhd' REFERENCES data_sources(id),
  PRIMARY KEY (job, run_date)
);
